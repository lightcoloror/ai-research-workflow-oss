def run_evals(config: ResearchConfig, data_dir: Path | None = None) -> dict[str, Any]:
    with TemporaryDirectory(prefix="research-evals-") as temp_root:
        root = data_dir or Path(temp_root)
        root.mkdir(parents=True, exist_ok=True)
        cases = [_run_case(case, config, root / case.name) for case in EVAL_CASES]
        return {
            "overall": _overall_status(cases),
            "data_dir": str(root),
            "case_count": len(cases),
            "cases": cases,
        }


def evals_to_markdown(result: dict[str, Any]) -> str:
    lines = ["# Research Workflow Evals", "", f"Overall: `{result.get('overall', 'unknown')}`", ""]
    for case in result.get("cases", []):
        lines.append(f"## {case.get('name')}")
        lines.append(f"- Status: `{case.get('status')}`")
        lines.append(f"- Claims extracted: `{case.get('claim_count')}` / expected `{case.get('expected_fact_count')}`")
        lines.append(f"- Revision suggestions: `{case.get('revision_suggestion_count', 0)}`")
        lines.append(f"- Coverage: `{case.get('claim_coverage')}`")
        lines.append(f"- Audit: `{case.get('audit_overall')}`")
        if case.get("failures"):
            for failure in case["failures"]:
                lines.append(f"- Failure: {failure}")
        lines.append("")
    return "\n".join(lines)


def _run_case(case: EvalCase, config: ResearchConfig, data_dir: Path) -> dict[str, Any]:
    result = run_research_pipeline(
        topic=case.topic,
        data_dir=data_dir,
        mode=case.mode,
        no_network=True,
        manual_evidence=case.manual_evidence,
        text_to_verify=case.text_to_verify,
        searxng_url=config.searxng_url,
        search_providers=config.search_providers,
    )
    claims = [claim.to_dict() for claim in result.claims]
    failures: list[str] = []
    coverage = round(len(claims) / max(1, case.expected_fact_count), 2)
    if coverage < case.min_claim_coverage:
        failures.append(f"claim coverage {coverage} is below {case.min_claim_coverage}")
    if result.audit.get("overall") != "ok":
        failures.append(f"audit overall is {result.audit.get('overall')}")
    for claim in result.claims:
        if claim.verdict == Verdict.SUPPORTED and not claim.evidence_ids:
            failures.append(f"supported claim has no evidence: {claim.text}")
    unsupported_texts = {claim.text for claim in result.claims if claim.verdict in {Verdict.CONTRADICTED, Verdict.NOT_FOUND}}
    report_payload = json.loads(result.report_json) if result.report_json else {}
    leaked_findings = [item for item in report_payload.get("findings", []) if item in unsupported_texts]
    if leaked_findings:
        failures.append(f"final findings include contradicted/not_found claims: {leaked_findings}")
    quote_types = {item.source_quote_type for item in result.evidence if item.source_quote_type}
    if result.evidence and quote_types == {"snippet"}:
        failures.append("evidence source_quote_type is only snippet")
    expected_verdicts = case.expected_verdicts or {}
    by_text = {claim.text: str(claim.verdict) for claim in result.claims}
    for text, expected in expected_verdicts.items():
        actual = by_text.get(text)
        if actual != str(expected):
            failures.append(f"expected verdict {expected} for {text!r}, got {actual or 'missing'}")
    expected_actions = case.expected_revision_actions or {}
    actions_by_text = {item.claim_text: item.action for item in result.revision_suggestions}
    for text, expected in expected_actions.items():
        actual = actions_by_text.get(text)
        if actual != expected:
            failures.append(f"expected revision action {expected} for {text!r}, got {actual or 'missing'}")
    return {
        "name": case.name,
        "status": "ok" if not failures else "error",
        "topic": case.topic,
        "mode": case.mode,
        "run_id": result.run_id,
        "report_path": result.report_path,
        "audit_overall": result.audit.get("overall"),
        "claim_count": len(claims),
        "expected_fact_count": case.expected_fact_count,
        "claim_coverage": coverage,
        "supported_count": sum(1 for claim in result.claims if claim.verdict == Verdict.SUPPORTED),
        "not_found_count": sum(1 for claim in result.claims if claim.verdict == Verdict.NOT_FOUND),
        "revision_suggestion_count": len(result.revision_suggestions),
        "revision_suggestions": [item.to_dict() for item in result.revision_suggestions],
        "claims": claims,
        "failures": failures,
    }


def _overall_status(cases: list[dict[str, Any]]) -> str:
    return "error" if any(case.get("status") == "error" for case in cases) else "ok"


def evals_to_json(result: dict[str, Any]) -> str:
    return json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True)
